class RealOllamaHandler(SimpleHTTPRequestHandler):
    def do_GET(self):
        self.send_response(200)
        self.send_header("Content-Type", "text/html")
        self.end_headers()
        self.wfile.write(HTML_CONTENT.encode('utf-8'))

    def do_POST(self):
        if self.path == '/chat':
            content_length = int(self.headers['Content-Length'])
            post_data = self.rfile.read(content_length)
            req_json = json.loads(post_data.decode('utf-8'))
            prompt = req_json.get('prompt', '')
            
            # Send REAL HTTP POST request to local Ollama on 11434
            ollama_payload = {
                "model": "sovereign-jarvis:latest",
                "prompt": prompt,
                "stream": False
            }
            
            try:
                ollama_req = urllib.request.Request(
                    OLLAMA_URL,
                    data=json.dumps(ollama_payload).encode('utf-8'),
                    headers={'Content-Type': 'application/json'}
                )
                with urllib.request.urlopen(ollama_req) as response:
                    res_data = json.loads(response.read().decode('utf-8'))
                    llm_text = res_data.get('response', 'No response from Ollama.')
            except Exception as e:
                llm_text = f"Ollama Bridge Error: {e}"
                
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"response": llm_text}).encode('utf-8'))

def launch():
    server = HTTPServer(('127.0.0.1', PORT), RealOllamaHandler)
    subprocess.Popen(["open", f"http://127.0.0.1:{PORT}"])
    server.serve_forever()

if __name__ == "__main__":
    launch()
