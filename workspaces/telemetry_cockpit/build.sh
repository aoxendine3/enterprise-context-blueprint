#!/usr/bin/env bash
# XORAS Telemetry Cockpit - the single canonical build entry point.
# Fail closed: any structural, signing, test, or coverage failure exits non-zero.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
DIST="$HERE/dist"
SRC="$HERE/src"

SIGNING_KEY="${XORAS_COCKPIT_SIGNING_KEY_PEM:-$HOME/.config/xoras/cockpit_bundle_signing/ed25519_priv.pem}"
SIGNING_PUB="${XORAS_COCKPIT_SIGNING_PUB_PEM:-$HOME/.config/xoras/cockpit_bundle_signing/ed25519_pub.pem}"

echo "[1/10] Sovereign file writer gate (must precede export: it writes SSOT)"
bash "$REPO/ops/scripts/verify_sovereign_file_writer.sh"

echo "[2/10] Monotonic build sequence + export from real SSOT: $REPO"
BUILD_SEQ="$(python3 - "$HOME/.config/xoras" <<'PY'
import fcntl, json, sys
from pathlib import Path
base = Path(sys.argv[1]); base.mkdir(parents=True, exist_ok=True)
path = base / 'cockpit_build_seq.json'
with open(path, 'a+', encoding='utf-8') as fh:
    fcntl.flock(fh.fileno(), fcntl.LOCK_EX)
    fh.seek(0)
    text = fh.read().strip()
    seq = int(json.loads(text)['last_seq']) + 1 if text else 1
    fh.seek(0); fh.truncate()
    fh.write(json.dumps({'last_seq': seq}, sort_keys=True) + '\n')
    fh.flush()
    import os
    os.fsync(fh.fileno())
    fcntl.flock(fh.fileno(), fcntl.LOCK_UN)
print(seq)
PY
)"
echo "build_seq=$BUILD_SEQ"
python3 "$HERE/tools/export_evidence_bundle.py" --repo-root "$REPO" \
  --out "$DIST/evidence-bundle.json" --build-seq "$BUILD_SEQ" \
  --known-good "$DIST/known_good_sources.json" --known-good-public-key "$SIGNING_PUB"

echo "[3/10] Signing evidence bundle (detached Ed25519)"
[ -r "$SIGNING_KEY" ] || { echo "signing key unreadable: $SIGNING_KEY" >&2; exit 1; }
[ -r "$SIGNING_PUB" ] || { echo "public key unreadable: $SIGNING_PUB" >&2; exit 1; }
python3 "$HERE/tools/sign_bundle.py" --bundle "$DIST/evidence-bundle.json" \
  --key "$SIGNING_KEY" --public-key "$SIGNING_PUB"

echo "[4/10] Structural verification of bundle"
python3 "$HERE/tools/verify_bundle.py" "$DIST/evidence-bundle.json"

echo "[5/10] Building pinned trust root (digest + signing public key)"
python3 - "$DIST" "$SIGNING_PUB" <<'PY'
import base64, json, sys
from pathlib import Path
from cryptography.hazmat.primitives import serialization
dist, pub_path = Path(sys.argv[1]), Path(sys.argv[2])
bundle = json.loads((dist / 'evidence-bundle.json').read_text(encoding='utf-8'))
public = serialization.load_pem_public_key(pub_path.read_bytes())
der = public.public_bytes(
    serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
trust = {
    'schema_version': 'xoras.cockpit.trust-root.v1',
    'algorithm': 'sha256',
    'pinned_bundle_digest': bundle['manifest']['digest'],
    'pinned_generator': bundle['generator']['tool'],
    'build_seq': bundle['build_seq'],
    'signature_algorithm': 'Ed25519',
    'signature_encoding': 'raw64-hex',
    'pinned_public_key_spki_b64': base64.b64encode(der).decode('ascii'),
}
(dist / 'trust_root.js').write_text(
    "/* GENERATED by build.sh - pinned trust root. */\n"
    "globalThis.XORAS_TRUST_ROOT = " + json.dumps(trust, sort_keys=True) + ";\n",
    encoding='utf-8')
print('Pinned digest:', trust['pinned_bundle_digest'])
print('Pinned SPKI b64:', trust['pinned_public_key_spki_b64'])
PY

echo "[6/10] Building single-file runtime from canonical modules"
{
  echo "/* GENERATED by build.sh - do not edit. Edit src/*.js instead. */"
  cat "$SRC/crypto.js" "$SRC/drift.js" "$SRC/state-machine.js" "$SRC/evidence-adapter.js" "$DIST/trust_root.js" "$SRC/app.js"
} > "$DIST/cockpit.js"

echo "[7/10] Writing asset lock"
python3 - "$DIST" <<'PY'
import hashlib, json, sys
from pathlib import Path
dist = Path(sys.argv[1])
names = ['index.html', 'cockpit.css', 'cockpit.js', 'evidence-bundle.json',
         'trust_root.js', 'known_good_sources.json']
lock = {
    'schema_version': 'xoras.cockpit.assets-lock.v1',
    'algorithm': 'sha256',
    'assets': {
        name: hashlib.sha256((dist / name).read_bytes()).hexdigest()
        for name in names
    },
}
(dist / 'assets.lock.json').write_text(
    json.dumps(lock, indent=2, sort_keys=True) + '\n', encoding='utf-8')
print(json.dumps(lock, indent=2, sort_keys=True))
PY

echo "[8/10] Verify shipped assets against lock"
python3 "$HERE/tools/verify_assets.py" "$DIST"

echo "[9/10] Layer 2 RAW assertion gate tests (Python)"
python3 -m unittest discover -s "$HERE/tests" -p 'test_*.py' -v

echo "[10/10] Full suite with ENFORCED coverage floor (GQS-022: 80% line)"
COVERAGE_OUTPUT="$(node --experimental-test-coverage --test "$HERE/tests/"*.test.mjs 2>&1)"
printf '%s\n' "$COVERAGE_OUTPUT"
LINE_COVERAGE="$(printf '%s\n' "$COVERAGE_OUTPUT" | awk -F'|' '/all files/ {gsub(/[ ]/,"",$2); print $2; exit}')"
if [ -z "$LINE_COVERAGE" ]; then
  echo "COVERAGE GATE FAILED: no coverage summary found" >&2
  exit 1
fi
python3 - "$LINE_COVERAGE" <<'PY'
import sys
value = float(sys.argv[1])
if value < 80.0:
    print(f"COVERAGE GATE FAILED: {value:.2f}% < 80%", file=sys.stderr)
    raise SystemExit(1)
print(f"COVERAGE GATE PASSED: {value:.2f}% >= 80%")
PY

echo "BUILD COMPLETE (structural). Product completion requires VERIFIED state, not merely a green build."
